// Simple helper to parse custom characters offline
export function convertTextToVocabularyOffline(text: string, limit: number = 10): { word: string; characters: { char: string; bopomofo: string }[] }[] {
  // Regex to match consecutive Chinese characters
  const words: string[] = [];
  let currentWord = '';
  
  for (const char of text) {
    if (/[\u4e00-\u9fa5]/.test(char)) {
      currentWord += char;
      if (currentWord.length === 2 || currentWord.length === 3 || currentWord.length === 4) {
        words.push(currentWord);
        currentWord = '';
      }
    } else {
      if (currentWord) {
        words.push(currentWord);
        currentWord = '';
      }
    }
  }
  if (currentWord) {
    words.push(currentWord);
  }

  // Filter out empty and extremely long words, slice to the requested limit
  const cleanWords = words.filter(w => w.length > 0 && w.length <= 4).slice(0, limit);

  // Map each character to Bopomofo
  return cleanWords.map(word => {
    const characters = Array.from(word).map(char => {
      // Find Bopomofo or guess based on general map or defaults
      let bopomofo = CHINESE_TO_BOPOMOFO_MAP[char] || 'ㄇㄚˊ'; // Gentle default if entirely missing
      return { char, bopomofo };
    });
    return { word, characters };
  });
}
